# Задание 1: описание чётного числа

# Просим пользователя ввести целое число
number = int(input("Введите целое число: "))

# Проверяем, чётное ли оно (остаток от деления на 2 равен 0)
if number % 2 == 0:
    # Число чётное. Теперь смотрим на знак.
    if number < 0:
        print("отрицательное четное число")
    elif number == 0:
        print("нулевое число")
    else:
        print("положительное четное число")
else:
    # Число нечётное — просто выводим сообщение
    print("число не является четным")